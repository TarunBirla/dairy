    /**
     * Bulk Deliver multiple customers
     */
    public function bulkDeliver(Request $request)
    {
        $customerIds = $request->input('customer_ids', []);
        $date = $request->input('date', Carbon::today()->format('Y-m-d'));
        $shift = $request->input('shift', 'morning');

        if (empty($customerIds)) {
            return response()->json(['success' => false, 'message' => 'No customers selected'], 422);
        }

        $updatedCount = DailyDelivery::whereIn('customer_id', $customerIds)
            ->whereDate('delivery_date', $date)
            ->where('shift', $shift)
            ->where('status', 'pending')
            ->update([
                'status' => 'delivered',
                'delivered_quantity' => DB::raw('quantity'),
                'delivered_at' => Carbon::now(),
            ]);

        return response()->json([
            'success' => true,
            'message' => "Successfully marked {$updatedCount} delivery items as delivered!",
            'delivered_at' => Carbon::now()->format('h:i A')
        ]);
    }

    /**
     * Receive Cash Payment
     */
    public function receiveCash(Request $request)
    {
        $validated = $request->validate([
            'customer_id' => 'required|exists:customers,id',
            'amount' => 'required|numeric|min:1',
            'payment_method' => 'nullable|string|in:cash,upi,bank,online',
            'notes' => 'nullable|string',
            'delivery_id' => 'nullable|exists:daily_deliveries,id',
            'date' => 'nullable|date',
        ]);

        $customer = Customer::findOrFail($validated['customer_id']);
        $amount = (float)$validated['amount'];
        $date = $validated['date'] ?? Carbon::today()->format('Y-m-d');
        $method = strtoupper($validated['payment_method'] ?? 'CASH');

        $newBalance = (float)$customer->current_balance - $amount;
        $customer->update(['current_balance' => $newBalance]);

        $ledger = CustomerLedger::create([
            'customer_id' => $customer->id,
            'transaction_date' => $date,
            'type' => 'credit',
            'amount' => $amount,
            'balance' => $newBalance,
            'reference_type' => 'delivery_cash',
            'reference_id' => $validated['delivery_id'] ?? null,
            'description' => "Doorstep Payment Received ({$method})" . ($request->filled('notes') ? " - " . $request->input('notes') : ''),
        ]);

        if (!empty($validated['delivery_id'])) {
            $del = DailyDelivery::find($validated['delivery_id']);
            if ($del) {
                $del->increment('cash_collected', $amount);
            }
        }

        return response()->json([
            'success' => true,
            'message' => "Payment of ₹" . number_format($amount, 2) . " received successfully!",
            'new_balance' => $newBalance,
            'amount' => $amount,
        ]);
    }

    /**
     * Skip delivery for a customer
     */
    public function skipCustomer(Request $request, Customer $customer)
    {
        $date = $request->input('date', Carbon::today()->format('Y-m-d'));
        $shift = $request->input('shift', 'morning');
        $reason = $request->input('reason', 'Customer unavailable / door locked');

        DailyDelivery::where('customer_id', $customer->id)
            ->whereDate('delivery_date', $date)
            ->where('shift', $shift)
            ->update([
                'status' => 'skipped',
                'failure_reason' => $reason,
            ]);

        return response()->json([
            'success' => true,
            'message' => "Delivery skipped: {$reason}"
        ]);
    }

    /**
     * Update delivery status (legacy fallback)
     */
    public function updateDeliveryStatus(Request $request, DailyDelivery $delivery)
    {
        $validated = $request->validate([
            'status' => 'required|in:delivered,skipped,failed',
            'cash_collected' => 'nullable|numeric|min:0',
            'failure_reason' => 'nullable|string',
            'notes' => 'nullable|string',
        ]);

        $status = $validated['status'];
        $cash = (float)($validated['cash_collected'] ?? 0);

        $delivery->update([
            'status' => $status,
            'delivered_quantity' => ($status === 'delivered') ? $delivery->quantity : 0,
            'cash_collected' => $cash,
            'failure_reason' => ($status !== 'delivered') ? ($validated['failure_reason'] ?? 'Customer unavailable') : null,
            'notes' => $validated['notes'] ?? null,
            'delivered_at' => ($status === 'delivered') ? Carbon::now() : null,
        ]);

        if ($status === 'delivered' && $cash > 0) {
            $customer = $delivery->customer;
            if ($customer) {
                $newBalance = (float)$customer->current_balance - $cash;
                $customer->update(['current_balance' => $newBalance]);

                CustomerLedger::create([
                    'customer_id' => $customer->id,
                    'transaction_date' => Carbon::today(),
                    'type' => 'credit',
                    'amount' => $cash,
                    'balance' => $newBalance,
                    'reference_type' => 'delivery_cash',
                    'reference_id' => $delivery->id,
                    'description' => "Cash Collected upon Delivery #{$delivery->id}",
                ]);
            }
        }

        return back()->with('success', "Delivery marked as " . ucfirst($status) . "!");
    }
