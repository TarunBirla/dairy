    /**
     * Main Delivery Entries Board (Simple Dairy Styled)
     */
    public function board(Request $request)
    {
        $date = $request->get('date', Carbon::today()->format('Y-m-d'));
        $shift = $request->get('shift', (date('H') >= 14) ? 'evening' : 'morning');
        $routeId = $request->get('route_id');
        $groupId = $request->get('group_id');
        $deliveryBoyId = $request->get('delivery_boy_id');
        $selectedStatus = $request->get('status', 'all');

        $carbonDate = Carbon::parse($date);

        // Auto-ensure daily deliveries exist for this date & shift
        $existingCount = DailyDelivery::whereDate('delivery_date', $date)
            ->where('shift', $shift)
            ->count();

        if ($existingCount === 0) {
            $this->autoGenerateDeliveries($carbonDate, $shift);
        }

        $query = DailyDelivery::with([
            'customer.groups',
            'customer.route',
            'customer.vacations',
            'product',
            'route',
            'deliveryBoy'
        ])
        ->whereDate('delivery_date', $date)
        ->where('shift', $shift);

        if ($routeId) {
            $query->where('route_id', $routeId);
        }

        if ($deliveryBoyId) {
            $query->where('delivery_boy_id', $deliveryBoyId);
        }

        if ($groupId) {
            $query->whereHas('customer.groups', function ($q) use ($groupId) {
                $q->where('customer_groups.id', $groupId);
            });
        }

        $deliveries = $query->get()->sortBy(function ($del) {
            return $del->customer->delivery_sequence ?? 999999;
        });

        // Group by Customer for Simple Dairy card/row layout
        $customersData = [];
        foreach ($deliveries as $del) {
            $c = $del->customer;
            if (!$c) continue;

            $cId = $c->id;
            if (!isset($customersData[$cId])) {
                $isOnVacation = $c->isOnVacation($carbonDate, $shift);
                $vacation = $isOnVacation ? $c->getVacationOn($carbonDate, $shift) : null;

                $customersData[$cId] = [
                    'id' => $c->id,
                    'code' => $c->customer_code,
                    'name' => $c->name,
                    'phone' => $c->phone,
                    'address' => $c->address,
                    'locality' => $c->locality ?: ($c->route ? $c->route->name : ''),
                    'current_balance' => (float)($c->current_balance ?? 0),
                    'route_id' => $c->route_id,
                    'route_name' => $c->route ? $c->route->name : ($del->route ? $del->route->name : ''),
                    'delivery_sequence' => $c->delivery_sequence ?? 999999,
                    'groups' => $c->groups ? $c->groups->pluck('name')->toArray() : [],
                    'group_names' => $c->groups ? $c->groups->pluck('name')->implode(', ') : '',
                    'is_on_vacation' => $isOnVacation,
                    'vacation_reason' => $vacation ? ($vacation->reason ?? 'Scheduled Leave') : null,
                    'items' => [],
                    'status' => 'pending',
                    'delivered_at' => null,
                    'failure_reason' => null,
                    'cash_collected' => 0.0,
                ];
            }

            $customersData[$cId]['items'][] = [
                'id' => $del->id,
                'product_id' => $del->product_id,
                'product_name' => $del->product ? $del->product->name : 'Milk',
                'product_unit' => $del->product ? $del->product->unit : 'Ltr',
                'quantity' => (float)$del->quantity,
                'unit_price' => (float)$del->unit_price,
                'total_amount' => (float)$del->total_amount,
                'status' => $del->status,
                'failure_reason' => $del->failure_reason,
                'cash_collected' => (float)$del->cash_collected,
                'delivered_at' => $del->delivered_at ? $del->delivered_at->format('h:i A') : null,
            ];

            $customersData[$cId]['cash_collected'] += (float)$del->cash_collected;
        }

        // Determine customer-level status
        foreach ($customersData as &$cData) {
            if ($cData['is_on_vacation']) {
                $cData['status'] = 'on_leave';
                $cData['failure_reason'] = $cData['vacation_reason'];
            } else {
                $itemStatuses = array_column($cData['items'], 'status');
                if (!empty($itemStatuses) && count(array_unique($itemStatuses)) === 1 && $itemStatuses[0] === 'delivered') {
                    $cData['status'] = 'delivered';
                    $cData['delivered_at'] = $cData['items'][0]['delivered_at'] ?? null;
                } elseif (!empty($itemStatuses) && in_array('skipped', $itemStatuses)) {
                    $cData['status'] = 'skipped';
                    $cData['failure_reason'] = $cData['items'][0]['failure_reason'] ?? 'Skipped';
                } else {
                    $cData['status'] = 'pending';
                }
            }
        }
        unset($cData);

        // Compute metrics
        $totalCustomers = count($customersData);
        $deliveredCount = count(array_filter($customersData, fn($c) => $c['status'] === 'delivered'));
        $pendingCount = count(array_filter($customersData, fn($c) => $c['status'] === 'pending'));
        $onLeaveCount = count(array_filter($customersData, fn($c) => in_array($c['status'], ['on_leave', 'skipped'])));
        $cashCollected = $deliveries->sum('cash_collected');

        $stats = [
            'total' => $totalCustomers,
            'delivered' => $deliveredCount,
            'pending' => $pendingCount,
            'on_leave' => $onLeaveCount,
            'cash_collected' => (float)$cashCollected,
            'total_items_count' => $deliveries->count(),
            'total_quantity' => (float)$deliveries->sum('quantity'),
        ];

        // Auxiliary data for filters and product change modals
        $products = Product::where('status', 'active')
            ->select('id', 'name', 'code', 'unit', 'price', 'subscription_price')
            ->orderBy('name')
            ->get();

        $routes = DeliveryRoute::where('status', 'active')->orderBy('name')->get();
        $groups = CustomerGroup::orderBy('name')->get();
        $deliveryBoys = User::where('role', User::ROLE_DELIVERY_BOY)->orderBy('name')->get();
        if ($deliveryBoys->isEmpty()) {
            $deliveryBoys = User::where('status', 'active')->orderBy('name')->get();
        }

        if ($request->wantsJson() || $request->has('ajax')) {
            return response()->json([
                'success' => true,
                'customers' => array_values($customersData),
                'stats' => $stats,
            ]);
        }

        return view('delivery.board', [
            'customersData' => array_values($customersData),
            'deliveries' => $deliveries,
            'products' => $products,
            'routes' => $routes,
            'groups' => $groups,
            'deliveryBoys' => $deliveryBoys,
            'date' => $date,
            'shift' => $shift,
            'routeId' => $routeId,
            'groupId' => $groupId,
            'deliveryBoyId' => $deliveryBoyId,
            'selectedStatus' => $selectedStatus,
            'stats' => $stats,
        ]);
    }

    /**
     * Auto-generate deliveries from active subscriptions
     */
    protected function autoGenerateDeliveries(Carbon $date, string $shift): int
    {
        $subscriptions = Subscription::where('status', 'active')->with(['customer.vacations', 'route'])->get();
        $generatedCount = 0;

        foreach ($subscriptions as $sub) {
            $customer = $sub->customer;
            if (!$customer) continue;

            $isOnVacation = $customer->isOnVacation($date, $shift);

            if (!$sub->shouldDeliverOn($date, $shift) && !$isOnVacation) {
                continue;
            }

            // Check if already generated for this date and subscription
            $exists = DailyDelivery::where('subscription_id', $sub->id)
                ->whereDate('delivery_date', $date)
                ->where('shift', $shift)
                ->exists();

            if (!$exists) {
                $status = $isOnVacation ? 'skipped' : 'pending';
                $vacation = $isOnVacation ? $customer->getVacationOn($date, $shift) : null;
                $failureReason = $isOnVacation ? 'Customer on vacation: ' . ($vacation->reason ?? 'Leave scheduled') : null;

                DailyDelivery::create([
                    'delivery_date' => $date->format('Y-m-d'),
                    'shift' => $shift,
                    'route_id' => $sub->route_id ?: $customer->route_id,
                    'delivery_boy_id' => $sub->route ? $sub->route->delivery_boy_id : ($customer->route ? $customer->route->delivery_boy_id : null),
                    'customer_id' => $sub->customer_id,
                    'subscription_id' => $sub->id,
                    'product_id' => $sub->product_id,
                    'quantity' => $sub->quantity,
                    'extra_quantity' => 0,
                    'delivered_quantity' => 0,
                    'unit_price' => $sub->unit_price,
                    'total_amount' => round($sub->quantity * $sub->unit_price, 2),
                    'status' => $status,
                    'failure_reason' => $failureReason,
                ]);
                $generatedCount++;
            }
        }

        return $generatedCount;
    }

    public function generateSchedule(Request $request)
    {
        $date = Carbon::parse($request->get('date', Carbon::today()));
        $shift = $request->get('shift', 'morning');

        $count = $this->autoGenerateDeliveries($date, $shift);

        return back()->with('success', "Generated {$count} delivery stops for {$date->format('d M Y')} ({$shift} shift)!");
    }

