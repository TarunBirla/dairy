    /**
     * Product Change / Edit Quantity on a Delivery Item
     */
    public function updateItem(Request $request, DailyDelivery $delivery)
    {
        $validated = $request->validate([
            'product_id' => 'required|exists:products,id',
            'quantity' => 'required|numeric|min:0.01',
            'unit_price' => 'nullable|numeric|min:0',
        ]);

        $product = Product::findOrFail($validated['product_id']);
        $quantity = (float)$validated['quantity'];
        $unitPrice = $request->filled('unit_price') 
            ? (float)$request->input('unit_price') 
            : (float)($product->subscription_price ?: $product->price);
        $total = round($quantity * $unitPrice, 2);

        $delivery->update([
            'product_id' => $product->id,
            'quantity' => $quantity,
            'delivered_quantity' => ($delivery->status === 'delivered') ? $quantity : 0,
            'unit_price' => $unitPrice,
            'total_amount' => $total,
        ]);

        $updatedDelivery = $delivery->fresh(['product']);

        return response()->json([
            'success' => true,
            'message' => 'Product updated successfully!',
            'item' => [
                'id' => $updatedDelivery->id,
                'product_id' => $updatedDelivery->product_id,
                'product_name' => $updatedDelivery->product ? $updatedDelivery->product->name : 'Milk',
                'product_unit' => $updatedDelivery->product ? $updatedDelivery->product->unit : 'Ltr',
                'quantity' => (float)$updatedDelivery->quantity,
                'unit_price' => (float)$updatedDelivery->unit_price,
                'total_amount' => (float)$updatedDelivery->total_amount,
                'status' => $updatedDelivery->status,
            ]
        ]);
    }

    /**
     * Add an extra product item to a customer's delivery
     */
    public function addItem(Request $request)
    {
        $validated = $request->validate([
            'customer_id' => 'required|exists:customers,id',
            'delivery_date' => 'required|date',
            'shift' => 'required|in:morning,evening',
            'product_id' => 'required|exists:products,id',
            'quantity' => 'required|numeric|min:0.01',
            'unit_price' => 'nullable|numeric|min:0',
        ]);

        $customer = Customer::findOrFail($validated['customer_id']);
        $product = Product::findOrFail($validated['product_id']);
        $quantity = (float)$validated['quantity'];
        $unitPrice = $request->filled('unit_price')
            ? (float)$request->input('unit_price')
            : (float)($product->subscription_price ?: $product->price);
        $total = round($quantity * $unitPrice, 2);

        $delivery = DailyDelivery::create([
            'delivery_date' => $validated['delivery_date'],
            'shift' => $validated['shift'],
            'customer_id' => $customer->id,
            'route_id' => $customer->route_id,
