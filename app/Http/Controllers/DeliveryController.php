    /**
     * Tap to Deliver: Marks all items for a customer as delivered
     */
    public function deliverCustomer(Request $request, Customer $customer)
    {
        $date = $request->input('date', Carbon::today()->format('Y-m-d'));
        $shift = $request->input('shift', 'morning');
        $cash = (float)$request->input('cash_collected', 0);

        $deliveries = DailyDelivery::where('customer_id', $customer->id)
            ->whereDate('delivery_date', $date)
            ->where('shift', $shift)
            ->get();

        foreach ($deliveries as $del) {
            $del->update([
                'status' => 'delivered',
                'delivered_quantity' => $del->quantity,
                'delivered_at' => Carbon::now(),
            ]);
        }

        if ($cash > 0) {
            $newBalance = (float)$customer->current_balance - $cash;
            $customer->update(['current_balance' => $newBalance]);

            CustomerLedger::create([
                'customer_id' => $customer->id,
                'transaction_date' => $date,
                'type' => 'credit',
                'amount' => $cash,
                'balance' => $newBalance,
                'reference_type' => 'delivery_cash',
                'reference_id' => $deliveries->first()?->id,
                'description' => "Cash collected upon doorstep delivery",
            ]);

            if ($deliveries->isNotEmpty()) {
                $deliveries->first()->update(['cash_collected' => $cash]);
            }
        }

        if ($request->wantsJson()) {
            return response()->json([
                'success' => true,
                'message' => 'Marked as delivered successfully!',
                'delivered_at' => Carbon::now()->format('h:i A'),
                'new_balance' => (float)$customer->fresh()->current_balance,
            ]);
        }

        return back()->with('success', "Customer {$customer->name} marked as delivered!");
    }

