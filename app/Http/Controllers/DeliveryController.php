            'extra_quantity' => $quantity,
            'delivered_quantity' => 0,
            'unit_price' => $unitPrice,
            'total_amount' => $total,
            'status' => 'pending',
        ]);

        $loaded = $delivery->load(['product']);

        return response()->json([
            'success' => true,
            'message' => 'Product added to delivery!',
            'item' => [
                'id' => $loaded->id,
                'product_id' => $loaded->product_id,
